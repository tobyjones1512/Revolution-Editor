import Foundation
import AppKit
import CoreText

/// Sprites and sounds found in a project's `assets/` folder (plus images used by the designer).
/// Their file names become `Sprite.<name>` / `Sound.<name>` in Swift and `SPRITE_<NAME>` /
/// `SOUND_<NAME>` in C.
nonisolated enum AssetCatalog {
    static let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "gif", "tiff", "bmp"]
    static let soundExtensions: Set<String> = ["wav", "wave", "aif", "aiff", "mp3", "m4a", "flac", "caf"]

    struct Asset { var name: String; var url: URL; var path: String }

    static func images(in project: URL) -> [Asset] { find(imageExtensions, in: project) }
    static func sounds(in project: URL) -> [Asset] { find(soundExtensions, in: project) }
    /// Streamed music: Mario Kart Wii / Brawl style .brstm files.
    static func music(in project: URL) -> [Asset] { find(["brstm"], in: project) }

    private static func find(_ exts: Set<String>, in project: URL) -> [Asset] {
        let dir = project.appendingPathComponent("assets", isDirectory: true)
        guard let walker = FileManager.default.enumerator(at: dir, includingPropertiesForKeys: nil, options: [.skipsHiddenFiles]) else { return [] }
        let root = project.resolvingSymlinksInPath().path + "/"
        let urls = walker.compactMap { $0 as? URL }.filter { exts.contains($0.pathExtension.lowercased()) }.sorted { $0.path < $1.path }
        return named(urls.map { ($0, $0.resolvingSymlinksInPath().path.replacingOccurrences(of: root, with: "")) })
    }

    /// Names from file names, made unique.
    static func named(_ files: [(URL, String)]) -> [Asset] {
        var used = Set<String>(), out: [Asset] = []
        for (url, path) in files {
            let base = UIDocument.identifier(url.deletingPathExtension().lastPathComponent)
            var name = base, n = 2
            while !used.insert(name).inserted { name = "\(base)\(n)"; n += 1 }
            out.append(Asset(name: name, url: url, path: path))
        }
        return out
    }
}

/// Turns a `UIDocument` and the project's assets into `ui_generated.h/.c`: widgets, a glyph atlas
/// per text size (drawn with the Mac's own Helvetica so labels match the designer), sprite
/// textures and sounds, all in the Wii's native formats.
nonisolated enum UICodegen {
    struct Output {
        var header: String
        var source: String
        var warnings: [String]
        var spriteNames: [String]
        var soundNames: [String]
        var musicNames: [String] = []
        var musicFiles: [URL] = []
        var screenNames: [String] = []
    }

    static let defaultFontSizes = [16, 20, 24, 28, 32, 40, 48]
    static let maxTexture = 1024
    static let soundRate = 32000

    static func generate(_ doc: UIDocument, projectRoot: URL) -> Output { generate(screens: [("main", doc)], projectRoot: projectRoot) }

    /// One or more UI screens (one `.wiiui` each). Their widgets are laid end to end in one table; a screen is a
    /// range of it, and only the current screen's range is drawn and clicked.
    static func generate(screens: [(name: String, doc: UIDocument)], projectRoot: URL) -> Output {
        var warnings: [String] = []
        let allWidgets = screens.flatMap { $0.doc.widgets }
        let doc = screens.first?.doc ?? UIDocument(background: .black, widgets: [])

        // Sprites: every image in assets/, plus any image a widget uses from elsewhere.
        var sprites = AssetCatalog.images(in: projectRoot)
        var spriteForPath: [String: Int] = [:]
        for (i, s) in sprites.enumerated() { spriteForPath[s.path] = i }
        var extra: [(URL, String)] = []
        for w in allWidgets where w.kind == .image && !w.imagePath.isEmpty && spriteForPath[w.imagePath] == nil {
            if !extra.contains(where: { $0.1 == w.imagePath }) { extra.append((projectRoot.appendingPathComponent(w.imagePath), w.imagePath)) }
        }
        var taken = Set(sprites.map(\.name))
        for a in AssetCatalog.named(extra) {
            var asset = a, n = 2
            while !taken.insert(asset.name).inserted { asset.name = "\(a.name)\(n)"; n += 1 }
            spriteForPath[asset.path] = sprites.count
            sprites.append(asset)
        }
        let sounds = AssetCatalog.sounds(in: projectRoot)
        let musics = AssetCatalog.music(in: projectRoot)

        var header = "/* ui_generated.h, generated by Revolution Editor. Do not edit. */\n#ifndef UI_GENERATED_H\n#define UI_GENERATED_H\n#include \"wiiui.h\"\n\n"
        header += "enum {\n" + (allWidgets.isEmpty ? "    UI__NONE = 0,\n" : allWidgets.enumerated().map { "    UI_\($0.element.name.uppercased()) = \($0.offset),\n" }.joined()) + "};\n"
        header += "enum {\n" + screens.enumerated().map { "    SCREEN_\($0.element.name.uppercased()) = \($0.offset),\n" }.joined() + "};\n"
        header += "enum {\n" + (sprites.isEmpty ? "    SPRITE__NONE = 0,\n" : sprites.enumerated().map { "    SPRITE_\($0.element.name.uppercased()) = \($0.offset),\n" }.joined()) + "};\n"
        header += "enum {\n" + (sounds.isEmpty ? "    SOUND__NONE = 0,\n" : sounds.enumerated().map { "    SOUND_\($0.element.name.uppercased()) = \($0.offset),\n" }.joined()) + "};\n"
        header += "enum {\n" + (musics.isEmpty ? "    MUSIC__NONE = 0,\n" : musics.enumerated().map { "    MUSIC_\($0.element.name.uppercased()) = \($0.offset),\n" }.joined()) + "};\n\n#endif\n"

        var src = "/* ui_generated.c, generated by Revolution Editor. Do not edit. */\n#include \"ui_generated.h\"\n\n"

        // Fonts
        let widgetSizes = Set(allWidgets.filter { $0.kind == .label || $0.kind == .button }.map(\.fontSize))
        let sizes = widgetSizes.union(defaultFontSizes).sorted()
        for size in sizes { src += fontSource(size: size) }
        src += "const wiiui_font *const wiiui_fonts[] = { " + sizes.map { "&font_\($0)" }.joined(separator: ", ") + " };\n"
        src += "const int wiiui_font_count = \(sizes.count);\n\n"

        // Sprites
        var textureBytes = 0
        var smooth = Set<Int>()
        for w in allWidgets where w.kind == .image { if let i = spriteForPath[w.imagePath] { smooth.insert(i) } }
        var spriteTable = ""
        for (i, a) in sprites.enumerated() {
            guard let img = loadImage(a.url) else {
                warnings.append("Couldn't load the image \(a.path); it's drawn as an empty box.")
                src += "static const unsigned char sprite_\(i)_data[32] __attribute__((aligned(32))) = {0};\n"
                spriteTable += "    { sprite_\(i)_data, 4, 4, 4, 4, WGFX_RGB5A3, 0, 0, {0} },\n"
                continue
            }
            if img.clamped { warnings.append("\(a.path) is larger than \(maxTexture) pixels and was shrunk to fit.") }
            guard let data = TextureCodec.encode(rgba: img.rgba, width: img.pw, height: img.ph, format: .rgb5a3) else { continue }
            textureBytes += data.count
            src += "static const unsigned char sprite_\(i)_data[] __attribute__((aligned(32))) = {\(list(data))};\n"
            spriteTable += "    { sprite_\(i)_data, \(img.w), \(img.h), \(img.pw), \(img.ph), WGFX_RGB5A3, \(smooth.contains(i) ? 1 : 0), 0, {0} },\n"
        }
        src += "\nwgfx_texture wiiui_sprites[] = {\n\(sprites.isEmpty ? "    { 0 }\n" : spriteTable)};\n"
        src += "const int wiiui_sprite_count = \(sprites.count);\n\n"
        if textureBytes > 12_000_000 { warnings.append("Images use \(textureBytes / 1_000_000) MB of texture memory; the Wii has about 24 MB in total.") }

        // Sounds
        var soundTable = ""
        for (i, a) in sounds.enumerated() {
            do {
                let (channels, rate) = try AudioFileImport.load(a.url, sampleRate: Double(soundRate))
                let frames = channels.map(\.count).min() ?? 0
                var pcm = [UInt8](); pcm.reserveCapacity(frames * 2 + 32)
                for f in 0..<frames {
                    let mixed = channels.reduce(0) { $0 + Int($1[f]) } / max(1, channels.count)
                    let v = UInt16(bitPattern: Int16(clamping: mixed))
                    pcm.append(UInt8(v >> 8)); pcm.append(UInt8(v & 0xFF))
                }
                let bytes = pcm.count
                while pcm.count % 32 != 0 || pcm.isEmpty { pcm.append(0) }
                if bytes > 1_500_000 { warnings.append("\(a.path) is long (\(bytes / (rate * 2)) s); sounds are kept in memory, so prefer short effects.") }
                src += "static const unsigned char sound_\(i)_data[] __attribute__((aligned(32))) = {\(list(Data(pcm)))};\n"
                soundTable += "    { sound_\(i)_data, \(pcm.count), \(rate) },\n"
            } catch {
                warnings.append("Couldn't read the sound \(a.path): \(error.localizedDescription)")
                soundTable += "    { 0, 0, \(soundRate) },\n"
            }
        }
        src += "\nconst wiiui_sound wiiui_sounds[] = {\n\(sounds.isEmpty ? "    { 0, 0, 0 }\n" : soundTable)};\n"
        src += "const int wiiui_sound_count = \(sounds.count);\n\n"

        // Music: each .brstm is linked in as data (see HomebrewGenerator.syncMusic) and decoded as it plays.
        var musicTable = ""
        for (i, a) in musics.enumerated() {
            src += "#include \"wiiui_music_\(i)_bin.h\"\n"
            musicTable += "    { wiiui_music_\(i)_bin, wiiui_music_\(i)_bin_size },\n"
            let bytes = (try? FileManager.default.attributesOfItem(atPath: a.url.path)[.size] as? Int) ?? 0
            if bytes > 8_000_000 { warnings.append("\(a.path) is \(bytes / 1_000_000) MB; music is kept in memory, so prefer shorter tracks.") }
        }
        src += "\nconst wiiui_music wiiui_musics[] = {\n\(musics.isEmpty ? "    { 0, 0 }\n" : musicTable)};\n"
        src += "const int wiiui_music_count = \(musics.count);\n\n"

        // Widgets
        var table = ""
        for w in allWidgets {
            let kind = ["rectangle": "WIIUI_RECT", "label": "WIIUI_LABEL", "button": "WIIUI_BUTTON", "image": "WIIUI_IMAGE"][w.kind.rawValue]!
            let hasText = w.kind == .label || w.kind == .button
            let f = w.fill.bytes, t = w.textColor.bytes
            table += "    { \(kind), \(Int(w.x.rounded())), \(Int(w.y.rounded())), \(Int(w.width.rounded())), \(Int(w.height.rounded())), "
            table += "{\(f[0]), \(f[1]), \(f[2])}, {\(t[0]), \(t[1]), \(t[2])}, \(cString(w.text)), "
            table += "\(hasText ? "&font_\(w.fontSize)" : "NULL"), \(w.kind == .image ? (spriteForPath[w.imagePath] ?? -1) : -1), \(w.visible ? 1 : 0) },\n"
        }
        src += "wiiui_widget wiiui_widgets[] = {\n\(allWidgets.isEmpty ? "    { 0 }\n" : table)};\n"
        src += "const int wiiui_widget_count = \(allWidgets.count);\n"
        var first = 0, screenTable = ""
        for sc in screens {
            let bg = sc.doc.background.bytes
            screenTable += "    { \(first), \(sc.doc.widgets.count), {\(bg[0]), \(bg[1]), \(bg[2])} },\n"
            first += sc.doc.widgets.count
        }
        src += "const int wiiui_screen_w = \(doc.screenWidth);\n"
        src += "const wiiui_screen wiiui_screens[] = {\n\(screenTable)};\n"
        src += "const int wiiui_screen_count = \(screens.count);\n"
        return Output(header: header, source: src, warnings: warnings, spriteNames: sprites.map(\.name), soundNames: sounds.map(\.name), musicNames: musics.map(\.name), musicFiles: musics.map(\.url), screenNames: screens.map(\.name))
    }

    static func cString(_ s: String, limit: Int = 127) -> String {
        var out = "\""
        for u in s.unicodeScalars.prefix(limit) {
            switch u {
            case "\\": out += "\\\\"
            case "\"": out += "\\\""
            case "\n": out += "\\n"
            case " "..."~": out.unicodeScalars.append(u)
            default: out += "?"
            }
        }
        return out + "\""
    }

    private static func list(_ data: Data) -> String { data.map { String($0) }.joined(separator: ",") }

    // MARK: Font atlas

    struct Glyph { var alpha: [UInt8]; var w: Int; var h: Int; var xoff: Int; var yoff: Int; var advance: Int }

    /// One IA8 atlas texture and glyph table for `size`.
    static func fontSource(size: Int) -> String {
        let (glyphs, lineHeight, ascent) = atlas(size: size)
        let width = size >= 32 ? 512 : 256
        var pos: [(Int, Int)] = [], x = 0, y = 0, rowH = 0
        for g in glyphs {
            if g.w == 0 { pos.append((0, 0)); continue }
            if x + g.w + 1 > width { x = 0; y += rowH + 1; rowH = 0 }
            pos.append((x, y)); x += g.w + 1; rowH = max(rowH, g.h)
        }
        let height = (y + rowH + 3) / 4 * 4
        var rgba = [UInt8](repeating: 0, count: width * height * 4)
        for (g, p) in zip(glyphs, pos) where g.w > 0 {
            for gy in 0..<g.h { for gx in 0..<g.w {
                let o = ((p.1 + gy) * width + p.0 + gx) * 4
                rgba[o] = 255; rgba[o + 1] = 255; rgba[o + 2] = 255; rgba[o + 3] = g.alpha[gy * g.w + gx]
            } }
        }
        let data = TextureCodec.encode(rgba: rgba, width: width, height: height, format: .ia8) ?? Data()
        var s = "static const unsigned char font\(size)_data[] __attribute__((aligned(32))) = {\(list(data))};\n"
        s += "static wiiui_font font_\(size) = { \(size), \(lineHeight), \(ascent), { font\(size)_data, \(width), \(height), \(width), \(height), WGFX_IA8, 0, 0, {0} }, {\n"
        for (g, p) in zip(glyphs, pos) { s += "    { \(p.0), \(p.1), \(g.w), \(g.h), \(g.xoff), \(g.yoff), \(g.advance) },\n" }
        return s + "} };\n\n"
    }

    /// ASCII 32...126, drawn with Helvetica at `size` px.
    static func atlas(size: Int) -> (glyphs: [Glyph], lineHeight: Int, ascent: Int) {
        let font = CTFontCreateWithName("Helvetica" as CFString, CGFloat(size), nil)
        let ascent = Int(ceil(CTFontGetAscent(font)))
        let lineHeight = ascent + Int(ceil(CTFontGetDescent(font)))
        var out: [Glyph] = []
        for code in 32...126 {
            var ch = UniChar(code)
            var glyph = CGGlyph()
            CTFontGetGlyphsForCharacters(font, &ch, &glyph, 1)
            var advance = CGSize.zero
            CTFontGetAdvancesForGlyphs(font, .horizontal, &glyph, &advance, 1)
            var rect = CGRect.zero
            CTFontGetBoundingRectsForGlyphs(font, .horizontal, &glyph, &rect, 1)
            let adv = Int(advance.width.rounded())
            if rect.isEmpty || code == 32 {
                out.append(Glyph(alpha: [], w: 0, h: 0, xoff: 0, yoff: 0, advance: adv)); continue
            }
            let x0 = Int(floor(rect.minX)) - 1, y0 = Int(floor(rect.minY)) - 1
            let w = Int(ceil(rect.maxX)) - x0 + 1, h = Int(ceil(rect.maxY)) - y0 + 1
            var pixels = [UInt8](repeating: 0, count: w * h)
            pixels.withUnsafeMutableBytes { buf in
                guard let ctx = CGContext(data: buf.baseAddress, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w,
                                          space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue) else { return }
                ctx.setFillColor(gray: 1, alpha: 1)
                var pos = CGPoint(x: CGFloat(-x0), y: CGFloat(-y0))
                CTFontDrawGlyphs(font, &glyph, &pos, 1, ctx)
            }
            // Memory row 0 is the top of the bitmap, i.e. y = y0 + h in glyph space.
            out.append(Glyph(alpha: pixels, w: w, h: h, xoff: x0, yoff: ascent - (y0 + h), advance: adv))
        }
        return (out, lineHeight, ascent)
    }

    // MARK: Images

    struct LoadedImage { var rgba: [UInt8]; var w: Int; var h: Int; var pw: Int; var ph: Int; var clamped: Bool }

    /// Straight-alpha RGBA, padded with transparent texels up to whole 4x4 tiles.
    static func loadImage(_ url: URL) -> LoadedImage? {
        guard let img = NSImage(contentsOf: url), let cg = img.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return nil }
        var w = cg.width, h = cg.height, clamped = false
        if max(w, h) > maxTexture {
            let k = Double(maxTexture) / Double(max(w, h))
            w = max(1, Int(Double(w) * k)); h = max(1, Int(Double(h) * k)); clamped = true
        }
        let pw = (w + 3) / 4 * 4, ph = (h + 3) / 4 * 4
        var premul = [UInt8](repeating: 0, count: pw * ph * 4)
        let ok = premul.withUnsafeMutableBytes { buf -> Bool in
            guard let ctx = CGContext(data: buf.baseAddress, width: pw, height: ph, bitsPerComponent: 8, bytesPerRow: pw * 4,
                                      space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return false }
            ctx.interpolationQuality = .high
            ctx.draw(cg, in: CGRect(x: 0, y: ph - h, width: w, height: h))   // top-left aligned in the padded area
            return true
        }
        guard ok else { return nil }
        for i in stride(from: 0, to: premul.count, by: 4) {
            let a = Int(premul[i + 3])
            if a > 0 && a < 255 { for c in 0..<3 { premul[i + c] = UInt8(min(255, Int(premul[i + c]) * 255 / a)) } }
        }
        return LoadedImage(rgba: premul, w: w, h: h, pw: pw, ph: ph, clamped: clamped)
    }
}
