import Foundation

/// Turns a `NodeGraph` into `logic_generated.c`: the `app_on_*` hooks `wiiui.c` calls, plus the
/// graph's variables. Exec wires become statements in order; data wires become expressions
/// evaluated where they're used, so a "Get" after a "Set" sees the new value.
nonisolated enum NodeCodegen {
    struct Failure: Error, LocalizedError {
        var messages: [String]
        var errorDescription: String? { messages.joined(separator: "\n") }
    }

    static func generate(_ g: NodeGraph, widgetNames: [String], spriteNames: [String] = [], soundNames: [String] = [], musicNames: [String] = [], screenNames: [String] = [], actorNames: [String] = [], globals: [GraphVariable] = []) throws -> String {
        var g = g
        g.optimizeForCodegen()      // dead blocks, unused variables, fixed maths: gone before any C is written
        var gen = Generator(g: g, widgets: Set(widgetNames), sprites: Set(spriteNames), sounds: Set(soundNames), musics: Set(musicNames), screens: Set(screenNames))
        gen.actors = actorNames
        gen.globals = Dictionary(globals.map { ($0.name, $0) }, uniquingKeysWith: { a, _ in a })
        return try gen.run()
    }

    /// `globals_generated.h/.c`: the variables marked Global, shared by every node file.
    static func globalsFiles(_ vars: [GraphVariable]) -> (header: String, source: String) {
        var h = "/* globals_generated.h, generated by Revolution Editor. Do not edit. */\n#ifndef GLOBALS_GENERATED_H\n#define GLOBALS_GENERATED_H\n#include \"wn.h\"\n\n"
        var c = "/* globals_generated.c, generated by Revolution Editor. Do not edit. */\n#include \"globals_generated.h\"\n\n"
        let helper = Generator(g: NodeGraph(), widgets: [], sprites: [], sounds: [], musics: [], screens: [])
        for v in vars {
            let id = v.globalCName
            switch v.type {
            case .number: h += "extern double \(id);\n"; c += "double \(id) = \(helper.number(v.initial));\n"
            case .text: h += "extern char \(id)[128];\n"; c += "char \(id)[128] = \(UICodegen.cString(v.initial));\n"
            case .vector: h += "extern wn_vec \(id);\n"; c += "wn_vec \(id) = \(helper.vectorLiteral(v.initial, constant: true));\n"
            case .bounds: h += "extern wn_bounds \(id);\n"; c += "wn_bounds \(id) = \(helper.boundsLiteral(v.initial, constant: true));\n"
            default: h += "extern int \(id);\n"; c += "int \(id) = \(v.initial.lowercased() == "yes" || v.initial == "1" ? 1 : 0);\n"
            }
        }
        return (h + "\n#endif\n", c)
    }

    /// `actors_generated.c`: every sprite actor's instances, spawn / update / draw functions. Each actor's graph variables
    /// are per instance; its On Spawn / On Update events run with `self`.
    static func generateActors(_ graphs: [(name: String, graph: NodeGraph)], widgetNames: [String], spriteNames: [String] = [], soundNames: [String] = [],
                               musicNames: [String] = [], screenNames: [String] = [], globals: [GraphVariable] = []) throws -> String {
        var out = "/* actors_generated.c, generated by Revolution Editor from the sprite actors. Do not edit. */\n#include \"ui_generated.h\"\n#include \"wn.h\"\n" + (globals.isEmpty ? "" : "#include \"globals_generated.h\"\n") + "\n"
        let names = graphs.map(\.name)
        for n in names { out += "void wn_spawn_\(n)(wn_vec pos);\nvoid wn_destroy_all_\(n)(void);\nint wn_bounds_hit_\(n)(wn_bounds b);\nint wn_bounds_inside_\(n)(wn_bounds b);\nint wn_hit_vs_\(n)(int (*other)(wn_bounds));\nint wn_touch_\(n)(const void *except, wn_vec p, int w, int h, int destroy);\n" }
        out += "\n"
        var errors: [String] = [], update = "", draw = ""
        for (name, original) in graphs {
            var graph = original
            graph.optimizeForCodegen()
            var gen = Generator(g: graph, widgets: Set(widgetNames), sprites: Set(spriteNames), sounds: Set(soundNames), musics: Set(musicNames), screens: Set(screenNames))
            gen.actors = names
            gen.globals = Dictionary(globals.map { ($0.name, $0) }, uniquingKeysWith: { a, _ in a })
            gen.actor = (name, graph.actorSprite ?? "")
            do { out += try gen.runActor() } catch let f as Failure { errors += f.messages.map { "\(name): \($0)" } }
            update += "    \(name)_update_all();\n"
            draw += "    \(name)_draw_all();\n"
        }
        if !errors.isEmpty { throw Failure(messages: errors) }
        out += "void wn_actors_update(void) {\n\(update)}\n\nvoid wn_actors_draw(void) {\n\(draw)}\n"
        return out
    }

    private struct Generator {
        let g: NodeGraph
        let widgets: Set<String>
        let sprites: Set<String>
        let sounds: Set<String>
        let musics: Set<String>
        let screens: Set<String>
        var errors: [String] = []
        var globals: [String: GraphVariable] = [:]                 // shared variables from every file, by name
        var actors: [String] = []                                  // names of every sprite actor in the project
        var actor: (name: String, sprite: String)?                  // set while generating a sprite actor
        var varPrefix: String { actor == nil ? "" : "self->" }

        init(g: NodeGraph, widgets: Set<String>, sprites: Set<String>, sounds: Set<String>, musics: Set<String>, screens: Set<String>) {
            self.g = g; self.widgets = widgets; self.sprites = sprites; self.sounds = sounds; self.musics = musics; self.screens = screens
        }

        static let buttonMacros = ["A": "WPAD_BUTTON_A", "B": "WPAD_BUTTON_B", "1": "WPAD_BUTTON_1", "2": "WPAD_BUTTON_2",
                                   "Plus": "WPAD_BUTTON_PLUS", "Minus": "WPAD_BUTTON_MINUS", "Up": "WPAD_BUTTON_UP",
                                   "Down": "WPAD_BUTTON_DOWN", "Left": "WPAD_BUTTON_LEFT", "Right": "WPAD_BUTTON_RIGHT"]
        func player(_ n: GraphNode) -> Int { (Int(n.params["player"] ?? "1") ?? 1) - 1 }

        mutating func run() throws -> String {
            var out = "/* logic_generated.c, generated by Revolution Editor from the node graph. Do not edit. */\n"
            out += "#include \"ui_generated.h\"\n#include \"wn.h\"\n"
            if !globals.isEmpty { out += "#include \"globals_generated.h\"\n" }
            out += "\n"
            if let fps = g.fps, fps != 60 { out += "extern const int wiiui_fps_setting;\nconst int wiiui_fps_setting = \(max(1, min(60, fps)));\n\n" }
            for a in actors { out += "void wn_spawn_\(a)(wn_vec pos);\nvoid wn_destroy_all_\(a)(void);\nint wn_bounds_hit_\(a)(wn_bounds b);\nint wn_bounds_inside_\(a)(wn_bounds b);\nint wn_hit_vs_\(a)(int (*other)(wn_bounds));\nint wn_touch_\(a)(const void *except, wn_vec p, int w, int h, int destroy);\n" }
            if !actors.isEmpty { out += "\n" }

            for v in g.variables where !v.global {
                let id = "v_" + UIDocument.identifier(v.name)
                switch v.type {
                case .number: out += "static double \(id) = \(number(v.initial));\n"
                case .text: out += "static char \(id)[128] = \(UICodegen.cString(v.initial));\n"
                case .vector: out += "static wn_vec \(id) = \(vectorLiteral(v.initial, constant: true));\n"
                case .bounds: out += "static wn_bounds \(id) = \(boundsLiteral(v.initial, constant: true));\n"
                default: out += "static int \(id) = \(v.initial.lowercased() == "yes" || v.initial == "1" ? 1 : 0);\n"
                }
            }
            out += "\n"

            let events = g.nodes.filter { $0.kind.isEvent }.sorted { ($0.y, $0.x) < ($1.y, $1.x) }
            var start = "", frame = "", draw = "", wpad = ""
            var buttons: [(widget: String, code: String)] = []
            var functions: [(name: String, code: String)] = []
            for n in events {
                var path: Set<String> = [n.id]
                let code = chain(from: n, port: "then", indent: 2, path: &path)
                switch n.kind {
                case .defineFunction:
                    let name = UIDocument.identifier(n.params["name"] ?? "")
                    if functions.contains(where: { $0.name == name }) { errors.append("Two functions are named \"\(name)\".") }
                    functions.append((name, code))
                case .onStart: start += code
                case .onFrame: frame += code
                case .onDraw: draw += code
                case .onButton:
                    let w = n.params["widget"] ?? ""
                    if !widgets.contains(w) { errors.append("\"On Button Pressed\" uses widget \"\(w)\", which isn't in the UI.") }
                    buttons.append((w, code))
                case .onWiimote:
                    let macro = Self.buttonMacros[n.params["button"] ?? "A"] ?? "WPAD_BUTTON_A"
                    wpad += "    if (pressed & \(macro)) {\n\(code)    }\n"
                case .onSpawn, .onUpdate: errors.append("\"\(n.kind.title)\" only works in a sprite actor file (set the graph type to Sprite Actor).")
                default: break
                }
            }
            if !errors.isEmpty { throw Failure(messages: errors) }

            if !functions.isEmpty {
                out += functions.map { "void fn_\($0.name)(void);\n" }.joined() + "\n"
                out += functions.map { "void fn_\($0.name)(void) {\n\($0.code)}\n\n" }.joined()
            }
            if !start.isEmpty { out += "void app_on_start(void) {\n\(start)}\n\n" }
            if !frame.isEmpty { out += "void app_on_frame(void) {\n\(frame)}\n\n" }
            if !draw.isEmpty { out += "void app_on_draw(void) {\n\(draw)}\n\n" }
            if !wpad.isEmpty { out += "void app_on_wpad(unsigned int pressed) {\n\(wpad)}\n\n" }
            if !buttons.isEmpty {
                out += "void app_on_button(int id) {\n    switch (id) {\n"
                for w in Array(Set(buttons.map(\.widget))).sorted() {
                    out += "    case UI_\(w.uppercased()): {\n" + buttons.filter { $0.widget == w }.map(\.code).joined() + "        break;\n    }\n"
                }
                out += "    default: break;\n    }\n}\n"
            }
            return out
        }

        /// One sprite actor: its instance pool plus spawn, update, draw and touch helpers.
        mutating func runActor() throws -> String {
            guard let a = actor else { return "" }
            let T = a.name, S = UIDocument.identifier(a.sprite)
            let hasSprite = !a.sprite.isEmpty       // no sprite: an invisible actor with a 32 x 32 hit box
            if hasSprite, !sprites.contains(a.sprite) { errors.append("the sprite \"\(a.sprite)\" isn't in the project's assets folder.") }
            var out = "/* ---- sprite actor \(T) ---- */\n#define \(T)_MAX 64\ntypedef struct {\n    int alive;\n    wn_vec pos;\n"
            var inits = ""
            for v in g.variables where !v.global {
                let id = "v_" + UIDocument.identifier(v.name)
                switch v.type {
                case .number: out += "    double \(id);\n"; inits += "        self->\(id) = \(number(v.initial));\n"
                case .text: out += "    char \(id)[128];\n"; inits += "        strncpy(self->\(id), \(UICodegen.cString(v.initial)), 127);\n"
                case .vector: out += "    wn_vec \(id);\n"; inits += "        self->\(id) = \(vectorLiteral(v.initial)); \n"
                case .bounds: out += "    wn_bounds \(id);\n"; inits += "        self->\(id) = \(boundsLiteral(v.initial));\n"
                default: out += "    int \(id);\n"; inits += "        self->\(id) = \(v.initial.lowercased() == "yes" || v.initial == "1" ? 1 : 0);\n"
                }
            }
            out += "} \(T)_t;\nstatic \(T)_t \(T)_pool[\(T)_MAX];\n\n"

            var onSpawn = "", onUpdate = ""
            for n in g.nodes.filter({ $0.kind.isEvent }).sorted(by: { ($0.y, $0.x) < ($1.y, $1.x) }) {
                var path: Set<String> = [n.id]
                let code = chain(from: n, port: "then", indent: 1, path: &path)
                switch n.kind {
                case .onSpawn: onSpawn += code
                case .onUpdate: onUpdate += code
                default: errors.append("\"\(n.kind.title)\" isn't available in a sprite actor; use On Spawn and On Update.")
                }
            }
            if !errors.isEmpty { throw Failure(messages: errors) }
            out += "static void \(T)_on_spawn(\(T)_t *self) {\n    (void)self;\n\(onSpawn)}\n\n"
            out += "static void \(T)_on_update(\(T)_t *self) {\n    (void)self;\n\(onUpdate)}\n\n"
            out += "void wn_spawn_\(T)(wn_vec pos) {\n    for (int i = 0; i < \(T)_MAX; i++) {\n        if (\(T)_pool[i].alive) continue;\n"
            out += "        \(T)_t *self = &\(T)_pool[i];\n        memset(self, 0, sizeof *self);\n        self->alive = 1;\n        self->pos = pos;\n\(inits)"
            out += "        \(T)_on_spawn(self);\n        return;\n    }\n}\n\n"
            out += "void wn_destroy_all_\(T)(void) {\n    for (int i = 0; i < \(T)_MAX; i++) \(T)_pool[i].alive = 0;\n}\n\n"
            out += "int wn_bounds_hit_\(T)(wn_bounds b) {\n"
            out += hasSprite ? "    int ow = wiiui_sprite_width(SPRITE_\(S.uppercased())), oh = wiiui_sprite_height(SPRITE_\(S.uppercased()));\n" : "    int ow = 32, oh = 32;\n"
            out += "    for (int i = 0; i < \(T)_MAX; i++) {\n        \(T)_t *o = &\(T)_pool[i];\n        if (!o->alive) continue;\n"
            out += "        if (b.x < o->pos.x + ow && o->pos.x < b.x + b.w && b.y < o->pos.y + oh && o->pos.y < b.y + b.h) return 1;\n    }\n    return 0;\n}\n\n"
            out += "int wn_bounds_inside_\(T)(wn_bounds b) {\n"
            out += hasSprite ? "    int ow = wiiui_sprite_width(SPRITE_\(S.uppercased())), oh = wiiui_sprite_height(SPRITE_\(S.uppercased()));\n" : "    int ow = 32, oh = 32;\n"
            out += "    for (int i = 0; i < \(T)_MAX; i++) {\n        \(T)_t *o = &\(T)_pool[i];\n        if (!o->alive) continue;\n"
            out += "        if (b.x >= o->pos.x && b.y >= o->pos.y && b.x + b.w <= o->pos.x + ow && b.y + b.h <= o->pos.y + oh) return 1;\n    }\n    return 0;\n}\n\n"
            out += "int wn_hit_vs_\(T)(int (*other)(wn_bounds)) {\n"
            out += hasSprite ? "    int ow = wiiui_sprite_width(SPRITE_\(S.uppercased())), oh = wiiui_sprite_height(SPRITE_\(S.uppercased()));\n" : "    int ow = 32, oh = 32;\n"
            out += "    for (int i = 0; i < \(T)_MAX; i++) {\n        \(T)_t *o = &\(T)_pool[i];\n        if (o->alive && other(wn_bounds_make(o->pos.x, o->pos.y, ow, oh))) return 1;\n    }\n    return 0;\n}\n\n"
            out += "int wn_touch_\(T)(const void *except, wn_vec p, int w, int h, int destroy) {\n    int hit = 0;\n"
            out += hasSprite ? "    int ow = wiiui_sprite_width(SPRITE_\(S.uppercased())), oh = wiiui_sprite_height(SPRITE_\(S.uppercased()));\n"
                             : "    int ow = 32, oh = 32;\n"
            out += "    for (int i = 0; i < \(T)_MAX; i++) {\n        \(T)_t *o = &\(T)_pool[i];\n        if (!o->alive || (const void *)o == except) continue;\n"
            out += "        if (p.x < o->pos.x + ow && o->pos.x < p.x + w && p.y < o->pos.y + oh && o->pos.y < p.y + h) { hit = 1; if (destroy) o->alive = 0; }\n    }\n    return hit;\n}\n\n"
            out += "static void \(T)_update_all(void) {\n    for (int i = 0; i < \(T)_MAX; i++) if (\(T)_pool[i].alive) \(T)_on_update(&\(T)_pool[i]);\n}\n\n"
            out += "static void \(T)_draw_all(void) {\n"
            if hasSprite {
                out += "    for (int i = 0; i < \(T)_MAX; i++) if (\(T)_pool[i].alive)\n"
                out += "        wiiui_draw_sprite(SPRITE_\(S.uppercased()), (int)\(T)_pool[i].pos.x, 480 - (int)\(T)_pool[i].pos.y - wiiui_sprite_height(SPRITE_\(S.uppercased())));\n"
            }
            out += "}\n\n"
            if !errors.isEmpty { throw Failure(messages: errors) }
            return out
        }

        /// The actor type named by a node's "actor" parameter (checked), for spawn / touch calls.
        mutating func actorParam(_ n: GraphNode) -> String {
            let a = n.params["actor"] ?? ""
            if !actors.contains(a) { errors.append("\"\(n.kind.title)\" uses the sprite actor \"\(a)\", which isn't a sprite actor file in the project.") }
            return a
        }

        /// `self` boxes for a sprite actor's own size.
        func selfSize() -> (String, String) {
            if (actor?.sprite ?? "").isEmpty { return ("32", "32") }
            let s = "SPRITE_" + UIDocument.identifier(actor?.sprite ?? "").uppercased()
            return ("wiiui_sprite_width(\(s))", "wiiui_sprite_height(\(s))")
        }

        mutating func requireActor(_ n: GraphNode) -> Bool {
            if actor == nil { errors.append("\"\(n.kind.title)\" only works in a sprite actor file."); return false }
            return true
        }

        // MARK: Expression folding. Operands are C expressions; a plain number literal is folded away.

        func lit(_ s: String) -> Double? { Double(s) }
        func numLit(_ d: Double) -> String { d == d.rounded() && abs(d) < 1e9 ? "\(Int(d)).0" : "\(d)" }
        /// `(int)(expr)`, or just the integer when expr is a literal.
        func asInt(_ s: String) -> String { lit(s).map { "\(Int($0))" } ?? "(int)(\(s))" }
        /// The arguments of a `wn_vec_make(a, b)` expression, when that is the whole string.
        func makeArgs(_ s: String) -> (String, String)? {
            let prefix = "wn_vec_make("
            guard s.hasPrefix(prefix), s.hasSuffix(")") else { return nil }
            let inner = Array(s.dropFirst(prefix.count).dropLast())
            var depth = 0, comma: Int?
            for (i, c) in inner.enumerated() {
                if c == "(" { depth += 1 } else if c == ")" { depth -= 1; if depth < 0 { return nil } }
                else if c == ",", depth == 0, comma == nil { comma = i }
            }
            guard depth == 0, let k = comma else { return nil }
            return (String(inner[..<k]).trimmingCharacters(in: .whitespaces), String(inner[(k + 1)...]).trimmingCharacters(in: .whitespaces))
        }

        /// The C name of variable `name`: this graph's own (static, or a field of `self` in an actor) or a shared one.
        mutating func varRef(_ name: String, node n: GraphNode) -> String {
            if let local = g.variables.first(where: { $0.name == name }), !local.global { return varPrefix + "v_" + UIDocument.identifier(name) }
            if let shared = globals[name] { return shared.globalCName }
            errors.append("\"\(n.kind.title)\" uses variable \"\(name)\", which isn't defined.")
            return varPrefix + "v_" + UIDocument.identifier(name)
        }

        /// "r, g, b" typed or picked on a node, as a C `wn_col`.
        func colourLiteral(_ s: String) -> String {
            let p = s.split(whereSeparator: { $0 == "," || $0 == " " }).map(String.init)
            let c = (0..<3).map { number($0 < p.count ? p[$0] : "255") }
            return "wn_col_make(\(c[0]), \(c[1]), \(c[2]))"
        }

        /// "x, y, w, h" typed on a node or variable, as a C `wn_bounds`.
        func boundsLiteral(_ s: String, constant: Bool = false) -> String {
            let p = s.split(whereSeparator: { $0 == "," || $0 == " " }).map(String.init)
            let v = (0..<4).map { number($0 < p.count ? p[$0] : ($0 >= 2 ? "32" : "0")) }.joined(separator: ", ")
            return constant ? "{ \(v) }" : "wn_bounds_make(\(v))"
        }

        /// "x, y" typed on a node or variable, as a C `wn_vec`.
        func vectorLiteral(_ s: String, constant: Bool = false) -> String {
            let p = s.split(whereSeparator: { $0 == "," || $0 == " " }).map(String.init)
            let xy = "\(number(p.first ?? "0")), \(number(p.count > 1 ? p[1] : "0"))"
            return constant ? "{ \(xy) }" : "wn_vec_make(\(xy))"
        }

        /// The top-left-origin y for something `h` tall whose y the user gave from the bottom.
        func flipY(_ y: String, _ h: String) -> String { g.yUp ? "(480 - (int)(\(y)) - (int)(\(h)))" : "(int)(\(y))" }

        func pad(_ n: Int) -> String { String(repeating: "    ", count: n) }

        func number(_ s: String) -> String {
            let d = Double(s.trimmingCharacters(in: .whitespaces)) ?? 0
            return d == d.rounded() && abs(d) < 1e9 ? "\(Int(d)).0" : "\(d)"
        }

        func edgeInto(_ n: GraphNode, _ port: String) -> GraphEdge? { g.edges.first { $0.toNode == n.id && $0.toPort == port } }
        func edgeFrom(_ n: GraphNode, _ port: String) -> GraphEdge? { g.edges.first { $0.fromNode == n.id && $0.fromPort == port } }

        mutating func chain(from n: GraphNode, port: String, indent: Int, path: inout Set<String>) -> String {
            guard let e = edgeFrom(n, port), let next = g.node(e.toNode) else { return "" }
            if path.contains(next.id) {
                errors.append("\"\(next.kind.title)\" runs itself in a loop. Use Repeat for loops.")
                return ""
            }
            path.insert(next.id)
            defer { path.remove(next.id) }
            return statement(next, indent: indent, path: &path)
        }

        mutating func statement(_ n: GraphNode, indent: Int, path: inout Set<String>) -> String {
            let p = pad(indent)
            func widget() -> String {
                let w = n.params["widget"] ?? ""
                if !widgets.contains(w) { errors.append("\"\(n.kind.title)\" uses widget \"\(w)\", which isn't in the UI.") }
                return "UI_\(w.uppercased())"
            }
            func variable() -> String {
                let v = n.params["variable"] ?? ""
                return varRef(v, node: n)
            }
            var code = ""
            switch n.kind {
            case .setText: code = "\(p)wiiui_set_text(\(widget()), \(input(n, "text")));\n"
            case .setVisible: code = "\(p)wiiui_set_visible(\(widget()), \(input(n, "visible")));\n"
            case .setColor:
                code = "\(p){ wn_col c = \(input(n, "colour")); wiiui_set_color(\(widget()), c.r, c.g, c.b); }\n"
            case .setNumberVar: code = "\(p)\(variable()) = \(input(n, "value"));\n"
            case .setTextVar:
                let v = variable()
                code = "\(p)strncpy(\(v), \(input(n, "value")), sizeof(\(v)) - 1);\n\(p)\(v)[sizeof(\(v)) - 1] = 0;\n"
            case .setBoolVar: code = "\(p)\(variable()) = (\(input(n, "value"))) ? 1 : 0;\n"
            case .toggleBoolVar: let v = variable(); code = "\(p)\(v) = !\(v);\n"
            case .setWidgetPosition:
                let w = "wiiui_widgets[\(widget())]", v = input(n, "position")
                code = "\(p){ wn_vec t = \(v); \(w).x = (int)t.x; \(w).y = " + (g.yUp ? "480 - (int)t.y - \(w).h" : "(int)t.y") + "; }\n"
            case .moveWidget:
                let w = "wiiui_widgets[\(widget())]", v = input(n, "by")
                code = "\(p){ wn_vec t = \(v); \(w).x += (int)t.x; \(w).y \(g.yUp ? "-=" : "+=") (int)t.y; }\n"
            case .setBoundsFromVectors: code = "\(p)\(variable()) = wn_bounds_from_vecs(\(input(n, "position")), \(input(n, "size")));\n"
            case .setVectorVar, .setBoundsVar: code = "\(p)\(variable()) = \(input(n, "value"));\n"
            case .spawnSprite:
                let a = actorParam(n)
                code = "\(p)wn_spawn_\(a)(\(input(n, "position")));\n"
            case .setSelfPosition:
                if requireActor(n) { code = "\(p)self->pos = \(input(n, "position"));\n" }
            case .moveSelf:
                if requireActor(n) { code = "\(p){ wn_vec t = \(input(n, "by")); self->pos.x += t.x; self->pos.y += t.y; }\n" }
            case .destroySelf:
                if requireActor(n) { code = "\(p){ self->alive = 0; return; }\n" }
                return code
            case .destroyAll:
                code = "\(p)wn_destroy_all_\(actorParam(n))();\n"
            case .destroyTouching:
                let a = actorParam(n)
                if requireActor(n) { let (w, h) = selfSize(); code = "\(p)wn_touch_\(a)(self, self->pos, \(w), \(h), 1);\n" }
            case .exitApp: code = "\(p)exit(0);\n"
            case .callFunction:
                let f = UIDocument.identifier(n.params["function"] ?? "")
                if !g.nodes.contains(where: { $0.kind == .defineFunction && UIDocument.identifier($0.params["name"] ?? "") == f }) {
                    errors.append("\"Call Function\" calls \"\(f)\", which isn't defined.")
                }
                code = "\(p)fn_\(f)();\n"
            case .drawRect:
                code = "\(p){ wn_vec p = \(input(n, "position")), s = \(input(n, "size")); wn_col c = \(input(n, "colour")); "
                    + "wiiui_draw_rect((int)p.x, \(flipY("p.y", "s.y")), (int)s.x, (int)s.y, c.r, c.g, c.b, \(asInt(input(n, "alpha")))); }\n"
            case .drawText:
                code = "\(p){ wn_vec p = \(input(n, "position")); wn_col c = \(input(n, "colour")); int sz = \(asInt(input(n, "size"))); "
                    + "wiiui_draw_text(sz, (int)p.x, \(flipY("p.y", "sz")), \(input(n, "text")), c.r, c.g, c.b, 255); }\n"
            case .drawSprite:
                let s = n.params["sprite"] ?? ""
                if !sprites.contains(s) { errors.append("\"Draw Sprite\" uses the sprite \"\(s)\", which isn't in the project's assets folder.") }
                code = "\(p){ wn_vec p = \(input(n, "position")); wiiui_draw_sprite(SPRITE_\(s.uppercased()), (int)p.x, \(flipY("p.y", "wiiui_sprite_height(SPRITE_\(s.uppercased()))"))); }\n"
            case .playSound:
                let s = n.params["sound"] ?? ""
                if !sounds.contains(s) { errors.append("\"Play Sound\" uses the sound \"\(s)\", which isn't in the project's assets folder.") }
                code = "\(p)wiiui_play_sound(SOUND_\(s.uppercased()));\n"
            case .playMusic:
                let m = n.params["music"] ?? ""
                if !musics.contains(m) { errors.append("\"Play Music\" uses the music \"\(m)\", which isn't a .brstm in the project's assets folder.") }
                code = "\(p)wiiui_play_music(MUSIC_\(m.uppercased()), \(n.params["loop"] == "No" ? 0 : 1));\n"
            case .switchScreen:
                let sc = n.params["screen"] ?? ""
                if !screens.contains(sc) { errors.append("\"Switch UI Screen\" uses the screen \"\(sc)\", which isn't a .wiiui file in the project.") }
                code = "\(p)wiiui_show_screen(SCREEN_\(sc.uppercased()));\n"
            case .stopMusic: code = "\(p)wiiui_stop_music();\n"
            case .branch:
                var t = path, f = path, d = path
                let cond = input(n, "condition")
                if let known = lit(cond) {           // the decision never changes: keep only the side that runs
                    code = known != 0 ? "\(p){\n" + chain(from: n, port: "true", indent: indent + 1, path: &t) + "\(p)}\n"
                                       : "\(p){\n" + chain(from: n, port: "false", indent: indent + 1, path: &f) + "\(p)}\n"
                    code += chain(from: n, port: "regardless", indent: indent, path: &d)
                    return code
                }
                let yes = chain(from: n, port: "true", indent: indent + 1, path: &t)
                let no = chain(from: n, port: "false", indent: indent + 1, path: &f)
                code = "\(p)if (\(cond)) {\n\(yes)\(p)}"
                code += no.isEmpty ? "\n" : " else {\n\(no)\(p)}\n"
                code += chain(from: n, port: "regardless", indent: indent, path: &d)
                return code
            case .repeatLoop:
                let i = "i_" + n.id.replacingOccurrences(of: "-", with: "").prefix(8)
                var b = path, d = path
                let body = chain(from: n, port: "body", indent: indent + 1, path: &b)
                code = "\(p)for (int \(i) = 0; \(i) < (int)(\(input(n, "count"))); \(i)++) {\n\(body)\(p)}\n"
                code += chain(from: n, port: "done", indent: indent, path: &d)
                return code
            default: return ""
            }
            return code + chain(from: n, port: "then", indent: indent, path: &path)
        }

        /// The C expression feeding data input `port` of `n`: the wired node's output, else the
        /// literal typed on the node, else a zero value.
        mutating func input(_ n: GraphNode, _ port: String) -> String { inputDeep(n, port, 0) }

        mutating func output(_ n: GraphNode, _ port: String, depth: Int) -> String {
            if depth > 64 { errors.append("A data wire loops back on itself."); return "0" }
            func a(_ p: String) -> String { inputDeep(n, p, depth + 1) }
            switch n.kind {
            case .number: return number(n.params["value"] ?? "0")
            case .textConst: return UICodegen.cString(n.params["text"] ?? "")
            case .boolConst: return n.params["value"] == "No" ? "0" : "1"
            case .screenSize: return "wn_vec_make(wiiui_screen_w, 480)"
            case .getSelfPosition: return requireActor(n) ? "self->pos" : "wn_vec_make(0, 0)"
            case .touchingSprite:
                let t = actorParam(n)
                if requireActor(n) { let (w, h) = selfSize(); return "wn_touch_\(t)(self, self->pos, \(w), \(h), 0)" }
                return "0"
            case .makeColour: return "wn_col_make(\(a("r")), \(a("g")), \(a("b")))"
            case .makeVector: return "wn_vec_make(\(a("x")), \(a("y")))"
            case .splitVector:
                let v = a("vector")
                if let (x, y) = makeArgs(v) { return port == "y" ? y : x }
                return "(\(v)).\(port == "y" ? "y" : "x")"
            case .addVectors: return "wn_vec_add(\(a("a")), \(a("b")))"
            case .subtractVectors: return "wn_vec_sub(\(a("a")), \(a("b")))"
            case .scaleVector: return "wn_vec_scale(\(a("vector")), \(a("by")))"
            case .vectorLength: return "wn_vec_len(\(a("vector")))"
            case .makeBoundsFromVectors: return "wn_bounds_from_vecs(\(a("position")), \(a("size")))"
            case .makeBounds: return "wn_bounds_make(\(a("x")), \(a("y")), \(a("width")), \(a("height")))"
            case .boundsInSprite:
                return "wn_bounds_\(n.params["inside"] == "Yes" ? "inside" : "hit")_\(actorParam(n))(\(a("bounds")))"
            case .spritesOverlap:
                let first = actorParam(n)
                let second = n.params["actor2"] ?? ""
                if !actors.contains(second) { errors.append("\"Sprites Overlap\" uses the sprite actor \"\(second)\", which isn't a sprite actor file in the project.") }
                return "wn_hit_vs_\(first)(wn_bounds_\(n.params["inside"] == "Yes" ? "inside" : "hit")_\(second))"
            case .getNumberVar, .getTextVar, .getBoolVar, .getVectorVar, .getBoundsVar:
                let v = n.params["variable"] ?? ""
                return varRef(v, node: n)
            case .getText:
                let w = n.params["widget"] ?? ""
                if !widgets.contains(w) { errors.append("\"Get Widget Text\" uses widget \"\(w)\", which isn't in the UI.") }
                return "wiiui_get_text(UI_\(w.uppercased()))"
            case .getWidgetPosition, .getWidgetSize:
                let w = n.params["widget"] ?? ""
                if !widgets.contains(w) { errors.append("\"\(n.kind.title)\" uses widget \"\(w)\", which isn't in the UI.") }
                let id = "wiiui_widgets[UI_\(w.uppercased())]"
                if n.kind == .getWidgetSize { return "wn_vec_make(\(id).w, \(id).h)" }
                return g.yUp ? "wn_vec_make(\(id).x, 480 - \(id).y - \(id).h)" : "wn_vec_make(\(id).x, \(id).y)"
            case .frameCount: return "((double)wiiui_frame_count())"
            case .repeatLoop: return "((double)i_" + n.id.replacingOccurrences(of: "-", with: "").prefix(8) + ")"
            case .add:
                let x = a("a"), y = a("b")
                if let p = lit(x), let q = lit(y) { return numLit(p + q) }
                if lit(y) == 0 { return x }
                if lit(x) == 0 { return y }
                return "(\(x) + \(y))"
            case .subtract:
                let x = a("a"), y = a("b")
                if let p = lit(x), let q = lit(y) { return numLit(p - q) }
                if lit(y) == 0 { return x }
                return "(\(x) - \(y))"
            case .multiply:
                let x = a("a"), y = a("b")
                if let p = lit(x), let q = lit(y) { return numLit(p * q) }
                if lit(y) == 1 { return x }
                if lit(x) == 1 { return y }
                return "(\(x) * \(y))"
            case .divide:
                let x = a("a"), y = a("b")
                if let q = lit(y) {
                    if q == 0 { return "0.0" }
                    if let p = lit(x) { return numLit(p / q) }
                    return q == 1 ? x : "(\(x) / \(y))"        // a fixed non-zero divisor needs no zero check
                }
                return "wn_div(\(x), \(y))"
            case .modulo:
                let x = a("a"), y = a("b")
                if let p = lit(x), let q = lit(y) { return numLit(q == 0 ? 0 : Double(Int64(p) % Int64(q))) }
                return "wn_mod(\(x), \(y))"
            case .compare:
                let x = a("a"), y = a("b"), op = n.params["op"] ?? "=="
                if let p = lit(x), let q = lit(y) {
                    switch op {
                    case "==": return p == q ? "1" : "0"
                    case "!=": return p != q ? "1" : "0"
                    case "<": return p < q ? "1" : "0"
                    case ">": return p > q ? "1" : "0"
                    case "<=": return p <= q ? "1" : "0"
                    default: return p >= q ? "1" : "0"
                    }
                }
                return "(\(x) \(op) \(y))"
            case .textEquals: return "(strcmp(\(a("a")), \(a("b"))) == 0)"
            case .and:
                let x = a("a"), y = a("b")
                if let p = lit(x), let q = lit(y) { return p != 0 && q != 0 ? "1" : "0" }
                return "(\(x) && \(y))"
            case .or:
                let x = a("a"), y = a("b")
                if let p = lit(x), let q = lit(y) { return p != 0 || q != 0 ? "1" : "0" }
                return "(\(x) || \(y))"
            case .not:
                let x = a("a")
                if let p = lit(x) { return p == 0 ? "1" : "0" }
                return "(!\(x))"
            case .numberToText: return "wn_num_text(\(a("number")))"
            case .boolToText: return "wn_bool_text(\(a("boolean")))"
            case .vectorToText: return "wn_vec_text(\(a("vector")))"
            case .colourToText: return "wn_col_text(\(a("colour")))"
            case .join: return "wn_join(\(a("a")), \(a("b")))"
            case .random: return "wn_random(\(a("min")), \(a("max")))"
            case .minimum:
                let x = a("a"), y = a("b")
                if let p = lit(x), let q = lit(y) { return numLit(min(p, q)) }
                return "wn_min(\(x), \(y))"
            case .maximum:
                let x = a("a"), y = a("b")
                if let p = lit(x), let q = lit(y) { return numLit(max(p, q)) }
                return "wn_max(\(x), \(y))"
            case .absolute:
                let x = a("a")
                if let p = lit(x) { return numLit(abs(p)) }
                return "wn_abs(\(x))"
            case .buttonHeld: return "((wiiui_held(\(player(n))) & \(Self.buttonMacros[n.params["button"] ?? "A"] ?? "WPAD_BUTTON_A")) != 0)"
            case .buttonPressed: return "((wiiui_pressed(\(player(n))) & \(Self.buttonMacros[n.params["button"] ?? "A"] ?? "WPAD_BUTTON_A")) != 0)"
            case .stickX: return "((double)wiiui_stick_x(\(player(n))))"
            case .stickY: return "((double)wiiui_stick_y(\(player(n))))"
            case .pointerX: return "wn_pointer(0)"
            case .pointerY: return g.yUp ? "(480 - wn_pointer(1))" : "wn_pointer(1)"
            case .sine, .cosine, .tangent:
                let fn = n.kind == .sine ? "sin" : (n.kind == .cosine ? "cos" : "tan")
                if let angle = lit(a("angle")) {
                    let r = n.params["unit"] == "Radians" ? angle : angle * Double.pi / 180
                    return numLit(n.kind == .sine ? sin(r) : (n.kind == .cosine ? cos(r) : tan(r)))
                }
                return "\(fn)((\(a("angle")))\(n.params["unit"] == "Radians" ? "" : " * 0.017453292519943295"))"
            case .overlaps:
                return "wiiui_rects_overlap(" + ["ax", "ay", "aw", "ah", "bx", "by", "bw", "bh"].map { "(int)(\(a($0)))" }.joined(separator: ", ") + ")"
            default: errors.append("\"\(n.kind.title)\" has no value to read."); return "0"
            }
        }

        mutating func inputDeep(_ n: GraphNode, _ port: String, _ depth: Int) -> String {
            guard let spec = n.kind.inputs.first(where: { $0.name == port }) else { return "0" }
            if let e = edgeInto(n, port), let src = g.node(e.fromNode) { return output(src, e.fromPort, depth: depth) }
            let literal = n.params[port]
            switch spec.type {
            case .number: return number(literal ?? "0")
            case .text: return UICodegen.cString(literal ?? "")
            case .vector: return vectorLiteral(literal ?? "")
            case .bounds: return boundsLiteral(literal ?? "")
            case .colour: return colourLiteral(literal ?? "")
            default: return (literal ?? "").lowercased() == "yes" || literal == "1" ? "1" : "0"
            }
        }
    }
