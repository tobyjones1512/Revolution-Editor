// Every table here is read from the retail game itself, not typed in by hand: the object names and
// resource lists from the USA disc's `Common.szs/ObjFlow.bin`, and which objects retail courses use
// (and always give a route) from every course.kmp on the disc. A previous hand-written name table
// had 25 of its 27 entries pointing at the wrong object (0xD8 labelled "Chain Chomp" is the
// Sherbet Land penguin), picking by name then placed something else entirely.

/// Every object ID retail Mario Kart Wii defines. Any other ID, notably 0, has no entry: the
/// game's ID->entry table returns -1 for it and the object is built from whatever precedes the
/// table, which crashes once a kart gets near it.
nonisolated let retailObjectIDRanges: [ClosedRange<UInt16>] = [
    0x001...0x018, 0x065...0x077, 0x0C9...0x0F3, 0x12D...0x18F,
    0x191...0x1AC, 0x1F5...0x21B, 0x259...0x261, 0x2BD...0x2F3,
]
nonisolated func isRetailObjectID(_ id: UInt16) -> Bool { retailObjectIDRanges.contains { $0.contains(id) } }

