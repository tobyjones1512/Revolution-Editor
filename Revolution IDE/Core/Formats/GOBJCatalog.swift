/// The friendly group an object belongs to, if any.
func gobjGroupName(_ objectID: UInt16) -> String? {
    gobjGroups.first { $0.ids.contains(objectID) && !$0.name.hasPrefix("Other") }?.name
}

/// "Penguin, penguin_m", or just the internal name when there's no friendly one.
func gobjFriendlyName(_ objectID: UInt16) -> String {
    let internalName = gobjDisplayName(objectID)
    guard let group = gobjGroupName(objectID) else { return internalName }
    return "\(group). \(internalName)"
}
